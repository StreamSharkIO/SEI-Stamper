#define NTP_EPOCH_DELTA 2208988800ULL
#define PAD 4

static void ntp_to_iso8601_frames(const ntp_timestamp_t *ntp,
                                  uint32_t fps_num, uint32_t fps_den,
                                  char *buf, size_t buf_size) {
  uint64_t unix_sec = (uint64_t)ntp->seconds - NTP_EPOCH_DELTA;

  /* Frame number — same calculation as ntp_to_smpte_timecode in sei-handler.c */
  uint64_t product = (uint64_t)ntp->fraction * (uint64_t)fps_num;
  uint64_t denom = (uint64_t)fps_den * 4294967296ULL;
  uint32_t frame = (uint32_t)(product / denom);
  uint32_t fps_ceil = (fps_num + fps_den - 1) / fps_den;
  if (fps_ceil > 0 && frame >= fps_ceil)
    frame = fps_ceil - 1;

  uint64_t s = unix_sec;
  int sec  = (int)(s % 60); s /= 60;
  int min  = (int)(s % 60); s /= 60;
  int hour = (int)(s % 24); s /= 24;

  /* Days since 1970-01-01 */
  int days = (int)s;
  int year = 1970;
  while (1) {
    int yd = (year % 4 == 0 && (year % 100 != 0 || year % 400 == 0)) ? 366 : 365;
    if (days < yd) break;
    days -= yd;
    year++;
  }
  int leap = (year % 4 == 0 && (year % 100 != 0 || year % 400 == 0));
  int mdays[] = {31, 28+leap, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31};
  int month = 0;
  while (month < 12 && days >= mdays[month]) {
    days -= mdays[month];
    month++;
  }

  snprintf(buf, buf_size, "%04d-%02d-%02dT%02d:%02d:%02d:%02uZ",
           year, month + 1, days + 1, hour, min, sec, frame);
}

static const uint8_t *get_glyph(char c) {
  if (c >= GLYPH_FIRST && c <= GLYPH_LAST)
    return font_data[c - GLYPH_FIRST];
  return font_data[0]; /* space for unknown */
}

static int get_scale(int height) {
  if (height >= 1080) return 3;
  if (height >= 720) return 2;
  return 1;
}

static void set_yuv_pixel_nv12(timecode_frame_t *f, int x, int y,
                                uint8_t yval, uint8_t uval, uint8_t vval) {
  if (x < 0 || x >= f->width || y < 0 || y >= f->height) return;
  f->data[0][y * f->linesize[0] + x] = yval;
  int cx = x / 2;
  int cy = y / 2;
  int uv_off = cy * f->linesize[1] + cx * 2;
  f->data[1][uv_off]     = uval;
  f->data[1][uv_off + 1] = vval;
}

static void set_yuv_pixel_420p(timecode_frame_t *f, int x, int y,
                                uint8_t yval, uint8_t uval, uint8_t vval) {
  if (x < 0 || x >= f->width || y < 0 || y >= f->height) return;
  f->data[0][y * f->linesize[0] + x] = yval;
  int cx = x / 2;
  int cy = y / 2;
  f->data[1][cy * f->linesize[1] + cx] = uval;
  f->data[2][cy * f->linesize[2] + cx] = vval;
}

static void draw_rect(timecode_frame_t *f, int x0, int y0, int w, int h,
                       uint8_t yval, uint8_t uval, uint8_t vval) {
  for (int y = y0; y < y0 + h && y < f->height; y++) {
    for (int x = x0; x < x0 + w && x < f->width; x++) {
      if (x < 0 || y < 0) continue;
      if (f->pixfmt == TC_PIX_NV12)
        set_yuv_pixel_nv12(f, x, y, yval, uval, vval);
      else
        set_yuv_pixel_420p(f, x, y, yval, uval, vval);
    }
  }
}

static void draw_char(timecode_frame_t *f, char c, int x0, int y0, int scale) {
  const uint8_t *glyph = get_glyph(c);
  for (int row = 0; row < GLYPH_H; row++) {
    uint8_t bits = glyph[row];
    for (int col = 0; col < GLYPH_W; col++) {
      if (bits & (0x80 >> col)) {
        for (int sy = 0; sy < scale; sy++) {
          for (int sx = 0; sx < scale; sx++) {
            int px = x0 + col * scale + sx;
            int py = y0 + row * scale + sy;
            if (f->pixfmt == TC_PIX_NV12)
              set_yuv_pixel_nv12(f, px, py, 235, 128, 128);
            else
              set_yuv_pixel_420p(f, px, py, 235, 128, 128);
          }
        }
      }
    }
  }
}

void timecode_render_draw(const ntp_timestamp_t *ntp,
                          uint32_t fps_num, uint32_t fps_den,
                          timecode_frame_t *frame,
                          timecode_position_t position) {
  if (!ntp || !frame || !frame->data[0] || !fps_num || !fps_den) return;

  char text[32];
  ntp_to_iso8601_frames(ntp, fps_num, fps_den, text, sizeof(text));
  int len = (int)strlen(text);

  int scale = get_scale(frame->height);
  int char_w = GLYPH_W * scale;
  int char_h = GLYPH_H * scale;
  int text_w = len * char_w;
  int text_h = char_h;
  int box_w = text_w + PAD * 2 * scale;
  int box_h = text_h + PAD * 2 * scale;

  int x0, y0;
  switch (position) {
  case TC_POS_TOP_LEFT:
    x0 = PAD * scale; y0 = PAD * scale; break;
  case TC_POS_TOP_CENTER:
    x0 = (frame->width - box_w) / 2; y0 = PAD * scale; break;
  case TC_POS_TOP_RIGHT:
    x0 = frame->width - box_w - PAD * scale; y0 = PAD * scale; break;
  case TC_POS_BOTTOM_LEFT:
    x0 = PAD * scale; y0 = frame->height - box_h - PAD * scale; break;
  case TC_POS_BOTTOM_CENTER:
    x0 = (frame->width - box_w) / 2; y0 = frame->height - box_h - PAD * scale; break;
  case TC_POS_BOTTOM_RIGHT:
    x0 = frame->width - box_w - PAD * scale; y0 = frame->height - box_h - PAD * scale; break;
  default:
    x0 = PAD * scale; y0 = PAD * scale; break;
  }

  /* Black background */
  draw_rect(frame, x0, y0, box_w, box_h, 16, 128, 128);

  /* White text */
  int tx = x0 + PAD * scale;
  int ty = y0 + PAD * scale;
  for (int i = 0; i < len; i++) {
    draw_char(frame, text[i], tx + i * char_w, ty, scale);
  }
}
